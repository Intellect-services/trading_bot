"""Base strategy module for implementing trading strategies."""

from typing import Dict, List, Any, Optional
import logging
import pandas as pd
from datetime import datetime
import numpy as np
from ..utils.config import Config
from ..core.data_feed import DataFeed
from ..core.portfolio import Portfolio
from src.core.risk_manager import RiskManager
from ..utils.logger import setup_logger

logger = setup_logger(__name__)


class Strategy:
    """Base class for trading strategies.

    Attributes:
        name (str): Name of the strategy
        config (Config): Configuration object containing strategy and risk parameters
        signals (List[pd.DataFrame]): List of historical signals generated by the strategy
        trades (List[Dict]): List of executed trades
        current_position (Dict[str, Any]): Current position information
        data (Dict[str, pd.DataFrame]): Dictionary to store historical data for each symbol
    """

    def __init__(self, config: Config):
        """Initialize the strategy with configuration parameters.

        Args:
            config: Configuration object containing strategy parameters
        """
        self.config = config
        self.name = "base_strategy"  # Default name, should be overridden by subclasses
        self.signals: List[pd.DataFrame] = []
        self.trades: List[Dict] = []
        self.current_position: Dict[str, Any] = {}
        self.data: Dict[str, pd.DataFrame] = {}
        self.logger = logger

        logger.info("Initialized %s strategy", self.name)

    def initialize_symbol(self, symbol: str, data: pd.DataFrame) -> None:
        """Initialize strategy for a symbol.
        
        Args:
            symbol: Symbol to initialize
            data: Historical data for the symbol
        """
        try:
            self.data[symbol] = data
            logger.info(f"Initialized strategy for {symbol}")
        except Exception as e:
            logger.error(f"Error initializing strategy for {symbol}: {e}")

    def generate_signals(self, data: pd.DataFrame) -> pd.DataFrame:
        """Generate trading signals based on the input data.

        Args:
            data (pd.DataFrame): Market data with OHLCV columns

        Returns:
            pd.DataFrame: DataFrame with signal column (-1 for sell, 0 for hold, 1 for buy)
        """
        try:
            # Calculate indicators
            data = self._calculate_indicators(data)
            
            # Generate signals
            signals = pd.DataFrame(index=data.index)
            signals["symbol"] = data.index.get_level_values(0) if isinstance(data.index, pd.MultiIndex) else data.index
            signals["signal"] = 0
            
            # Buy signal: SMA20 crosses above SMA50
            buy_signal = (data["sma_20"] > data["sma_50"]) & (data["rsi"] < 70)
            signals.loc[buy_signal, "signal"] = 1
            
            # Sell signal: SMA20 crosses below SMA50
            sell_signal = (data["sma_20"] < data["sma_50"]) & (data["rsi"] > 30)
            signals.loc[sell_signal, "signal"] = -1
            
            logger.debug(f"Generated signals: {signals}")
            return signals
        except Exception as e:
            logger.error(f"Error generating signals: {e}")
            return pd.DataFrame()

    def _calculate_indicators(self, data: pd.DataFrame) -> pd.DataFrame:
        """Calculate technical indicators.
        
        Args:
            data: Market data to calculate indicators for
            
        Returns:
            DataFrame with added indicators
        """
        try:
            # Calculate SMA
            data["sma_20"] = data["close"].rolling(window=20).mean()
            data["sma_50"] = data["close"].rolling(window=50).mean()
            
            # Calculate RSI
            delta = data["close"].diff()
            gain = delta.where(delta.gt(0), 0).rolling(window=14).mean()
            loss = -delta.where(delta.lt(0), 0).rolling(window=14).mean()
            rs = gain / loss
            data["rsi"] = 100 - (100 / (1 + rs))
            
            return data
        except Exception as e:
            logger.error(f"Error calculating indicators: {e}")
            return data

    def update_position(
        self, symbol: str, quantity: float, price: float, side: str
    ) -> None:
        """Update the current position after a trade execution.

        Args:
            symbol (str): Trading symbol
            quantity (float): Trade quantity
            price (float): Execution price
            side (str): Trade side ('buy' or 'sell')
        """
        trade = {
            "timestamp": datetime.now(),
            "symbol": symbol,
            "quantity": quantity,
            "price": price,
            "side": side,
        }
        self.trades.append(trade)

        if side == "buy":
            if symbol not in self.current_position:
                self.current_position[symbol] = {"quantity": 0, "avg_price": 0}
            current = self.current_position[symbol]
            total_quantity = current["quantity"] + quantity
            total_cost = (current["quantity"] * current["avg_price"]) + (
                quantity * price
            )
            current["avg_price"] = (
                total_cost / total_quantity if total_quantity > 0 else 0
            )
            current["quantity"] = total_quantity
        else:  # sell
            if symbol in self.current_position:
                self.current_position[symbol]["quantity"] -= quantity
                if self.current_position[symbol]["quantity"] <= 0:
                    del self.current_position[symbol]

        logger.info(
            "Updated position for %s: %s",
            symbol,
            self.current_position.get(symbol, "No position"),
        )

    def calculate_position_size(self, price: float, account_value: float) -> float:
        """Calculate the position size based on risk parameters.

        Args:
            price (float): Current market price
            account_value (float): Current account value

        Returns:
            float: Position size in base currency
        """
        max_position_size = self.config.get('max_position_size', 0.1)
        return (account_value * max_position_size) / price

    @staticmethod
    def format_price(price: float, decimals: int = 2) -> str:
        """Format price with specified decimal places.

        Args:
            price (float): Price to format
            decimals (int, optional): Number of decimal places. Defaults to 2.

        Returns:
            str: Formatted price string
        """
        return f"{price:.{decimals}f}"
