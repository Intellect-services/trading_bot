"""Base strategy module for implementing trading strategies."""
from typing import Dict, List, Any
import logging
import pandas as pd
from datetime import datetime

logger = logging.getLogger(__name__)


class Strategy:
    """Base class for trading strategies.

    Attributes:
        name (str): Name of the strategy
        config (dict): Configuration dictionary containing strategy and risk parameters
        signals (List[pd.DataFrame]): List of historical signals generated by the strategy
        trades (List[Dict]): List of executed trades
        current_position (Dict[str, Any]): Current position information
    """

    def __init__(self, config: Dict[str, Any]):
        """Initialize the strategy with configuration parameters.

        Args:
            config (Dict[str, Any]): Configuration dictionary containing strategy and risk parameters
        """
        self.config = config
        self.name = config['strategy']['name']
        self.signals: List[pd.DataFrame] = []
        self.trades: List[Dict] = []
        self.current_position: Dict[str, Any] = {}

        logger.info("Initialized %s strategy", self.name)

    def generate_signals(self, data: pd.DataFrame) -> pd.DataFrame:
        """Generate trading signals based on the input data.

        Args:
            data (pd.DataFrame): Market data with OHLCV columns

        Returns:
            pd.DataFrame: DataFrame with signal column (-1 for sell, 0 for hold, 1 for buy)
        """
        raise NotImplementedError("Subclasses must implement generate_signals method")

    def update_position(self, symbol: str, quantity: float, price: float, side: str) -> None:
        """Update the current position after a trade execution.

        Args:
            symbol (str): Trading symbol
            quantity (float): Trade quantity
            price (float): Execution price
            side (str): Trade side ('buy' or 'sell')
        """
        trade = {
            'timestamp': datetime.now(),
            'symbol': symbol,
            'quantity': quantity,
            'price': price,
            'side': side
        }
        self.trades.append(trade)

        if side == 'buy':
            if symbol not in self.current_position:
                self.current_position[symbol] = {'quantity': 0, 'avg_price': 0}
            current = self.current_position[symbol]
            total_quantity = current['quantity'] + quantity
            total_cost = (current['quantity'] * current['avg_price']) + (quantity * price)
            current['avg_price'] = total_cost / total_quantity if total_quantity > 0 else 0
            current['quantity'] = total_quantity
        else:  # sell
            if symbol in self.current_position:
                self.current_position[symbol]['quantity'] -= quantity
                if self.current_position[symbol]['quantity'] <= 0:
                    del self.current_position[symbol]

        logger.info("Updated position for %s: %s", symbol, self.current_position.get(symbol, 'No position'))

    def calculate_position_size(self, price: float) -> float:
        """Calculate the position size based on risk parameters.

        Args:
            price (float): Current market price

        Returns:
            float: Position size in base currency
        """
        max_position_size = self.config['risk']['max_position_size']
        return max_position_size

    @staticmethod
    def format_price(price: float, decimals: int = 2) -> str:
        """Format price with specified decimal places.

        Args:
            price (float): Price to format
            decimals (int, optional): Number of decimal places. Defaults to 2.

        Returns:
            str: Formatted price string
        """
        return f"{price:.{decimals}f}" 